// Build app/gr8r.css from the vendored gr8r-studio stylesheets (styles/gr8r,
// copied verbatim from github.com/gr8rstudio/gr8r-studio src/styles — the user
// owns that repo). Run after editing anything under styles/gr8r:
//
//   node scripts/build-gr8r-css.mjs
//
// The transform keeps gr8r's rules byte-for-byte in spirit but makes them
// coexist with the rest of the app:
//   • every selector is scoped under `.g8` (the shell root carries it);
//   • every custom property is renamed `--x` → `--g8-x`, so gr8r's
//     `--accent` (indigo) / `--border` never collide with our shadcn tokens;
//   • `:root` → `.g8`; `html` / `body` → `.g8`; `:root[data-theme='dark']`
//     → `.dark .g8` (next-themes puts `.dark` on <html>); the
//     prefers-color-scheme dark copies are dropped (next-themes resolves
//     "system" to the `.dark` class); `:root[data-accent|motion|side|density]`
//     → `.g8[data-…]`;
//   • the whole file lives in `@layer components`, so Tailwind utilities on
//     our own components (inside gr8r containers) still win, and gr8r's
//     element resets never beat a utility class.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, "..", "styles", "gr8r");
const out = join(here, "..", "app", "gr8r.css");

const index = readFileSync(join(srcDir, "index.css"), "utf8");
const files = [...index.matchAll(/@import\s+'\.\/([^']+)'/g)].map((m) => m[1]);
const css = files.map((f) => `/* ── ${f} ── */\n` + readFileSync(join(srcDir, f), "utf8")).join("\n");

const renameVars = (value) => value.replace(/--([a-zA-Z])/g, "--g8-$1");

function scopeSelector(sel) {
  let s = sel.trim();
  if (s.startsWith(".g8")) return s;
  // Theme / pref attributes on :root.
  s = s.replace(/:root\[data-theme=['"]dark['"]\]/g, ".dark .g8");
  s = s.replace(/:root\[data-theme=['"]light['"]\]/g, ".g8");
  s = s.replace(/:root:not\(\[data-theme=['"]light['"]\]\)/g, ".dark .g8");
  s = s.replace(/:root(\[data-(?:accent|motion|side|density)[^\]]*\])/g, ".g8$1");
  if (s.startsWith(".dark .g8") || s.startsWith(".g8[")) return s;
  if (s === ":root" || s === "html" || s === "body" || s === "#app") return ".g8";
  if (s.startsWith(":root ")) return ".g8 " + s.slice(6);
  if (/^(html|body)\b/.test(s)) return ".g8" + s.replace(/^(html|body)/, "");
  return ".g8 " + s;
}

const plugin = {
  postcssPlugin: "gr8r-scope",
  Once(root) {
    root.walkAtRules("media", (at) => {
      // Dark comes from `.dark` (next-themes), not the OS media query.
      if (/prefers-color-scheme:\s*dark/.test(at.params)) at.remove();
    });
    root.walkRules((rule) => {
      const parent = rule.parent;
      if (parent && parent.type === "atrule" && /keyframes$/.test(parent.name)) return;
      rule.selectors = rule.selectors.map(scopeSelector);
    });
    root.walkDecls((decl) => {
      if (decl.prop.startsWith("--")) decl.prop = renameVars(decl.prop);
      decl.value = renameVars(decl.value);
    });
  },
};

const result = await postcss([plugin]).process(css, { from: undefined });
const header = `/* GENERATED by scripts/build-gr8r-css.mjs from styles/gr8r — do not edit.
   gr8r-studio's design system, scoped under .g8 (see the script header). */
`;
// Geist via next/font: point gr8r's font tokens at our loaded faces.
const fontFix = `
.g8 {
  --g8-font: var(--font-geist), ui-sans-serif, -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
  --g8-mono: var(--font-geist-mono), ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;
}
`;
writeFileSync(out, `${header}@layer components {\n${result.css}\n${fontFix}}\n`);
console.log(`wrote ${out} (${files.length} files)`);
